import { access, readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'dist');
for (const file of ['index.html', 'app.js', 'styles.css', 'data.js', 'openyamm-data.js', 'items-data.js', 'mm7-data.js', 'mm7-travel-data.js', 'sw.js', 'manifest.webmanifest']) await access(path.join(dist, file));
for (const file of ['globe/index.html', 'globe/img/world.webp', 'globe/img/enroth.webp', 'globe/img/jadame.webp', 'globe/img/antagarich.webp']) await access(path.join(dist, file));
const globe = await readFile(path.join(dist, 'globe/index.html'), 'utf8');
for (const [, image] of globe.matchAll(/"img":"(maps\/[^"]+)"/g)) await access(path.join(dist, 'globe', image));
const data = await readFile(path.join(dist, 'data.js'), 'utf8');
const match = data.match(/^window\.ATLAS_PAGES=(.*);\s*$/s);
if (!match) throw new Error('Invalid data bundle');
const pages = JSON.parse(match[1]);
if (pages.length < 70) throw new Error(`Expected a complete mirror; found ${pages.length} pages`);
for (const page of pages) for (const image of page.images) await access(path.join(dist, 'assets/places', image));
const mapped = await readFile(path.join(dist, 'openyamm-data.js'), 'utf8');
const mappedMatch = mapped.match(/^window\.OPENYAMM=(.*);\s*$/s);
if (!mappedMatch) throw new Error('Invalid OpenYAMM data bundle');
const openyamm = JSON.parse(mappedMatch[1]);
if (openyamm.maps.length !== 15) throw new Error('Expected 15 high-resolution region maps');
if (openyamm.maps.reduce((count, map) => count + map.pois.length, 0) < 600) throw new Error('Missing mapped locations');
const itemSource = await readFile(path.join(dist, 'items-data.js'), 'utf8');
const itemMatch = itemSource.match(/^window\.ATLAS_ITEMS=(.*);\s*$/s);
if (!itemMatch) throw new Error('Invalid item data bundle');
const itemData = JSON.parse(itemMatch[1]);
if (itemData.items.filter(item => item.kind === 'Artifact').length !== 15 || itemData.items.filter(item => item.kind === 'Relic').length !== 15) throw new Error('Incomplete MM6 unique-item catalog');
if (!itemData.exchanges.some(item => item.item === 'Cobra Eggs' && item.gold === 300 && item.poi === 'h1328')) throw new Error('Missing Cobra Egg turn-in');
if (!itemData.exchanges.some(item => item.item === 'Whisp wrappings' && item.kind === 'quest')) throw new Error('Missing wrappings quest');
for (const map of openyamm.maps) {
  await access(path.join(dist, map.image));
  if (map.region !== map.sourceName) throw new Error(`Map is not using OpenYAMM's region name: ${map.id}`);
  if (!pages.some(page => page.region === map.region)) throw new Error(`Unknown mapped region: ${map.region}`);
  if (map.width < 1024 || map.height < 1024) throw new Error(`Map is too small: ${map.region}`);
  for (const poi of map.pois) if (poi.u < 0 || poi.u > 1 || poi.v < 0 || poi.v > 1) throw new Error(`Invalid point on ${map.region}`);
}
const serviceWorker = await readFile(path.join(dist, 'sw.js'), 'utf8');
if (serviceWorker.includes('__PRECACHE__') || !serviceWorker.includes('assets/places/World/big.jpg')) throw new Error('Offline cache manifest was not generated');
const assets = await readdir(path.join(dist, 'assets/places'));
if (!assets.length) throw new Error('Missing mirrored assets');
const mm7Source = await readFile(path.join(dist, 'mm7-data.js'), 'utf8');
const mm7Match = mm7Source.match(/^window\.MM7_PAGES=(.*);\s*$/s);
if (!mm7Match) throw new Error('Invalid MM7 data bundle');
const mm7Pages = JSON.parse(mm7Match[1]);
if (mm7Pages.length < 95 || mm7Pages.filter(page => page.id.startsWith('maps/')).length < 60) throw new Error('Incomplete MM7 page mirror');
const mm7Ids = new Set(mm7Pages.map(page => page.id));
for (const page of mm7Pages) {
  await access(path.join(dist, 'assets/mm7', page.sourcePath));
  for (const [, image] of page.html.matchAll(/src="(assets\/mm7\/[^"]+)"/g)) await access(path.join(dist, image));
  for (const [, target] of page.html.matchAll(/href="#\/mm7\/([^?"#]+)[^"]*"/g)) if (!mm7Ids.has(target)) throw new Error(`Broken MM7 guide link from ${page.id} to ${target}`);
}
if (!mm7Pages.some(page => page.id === 'items' && page.entries.some(entry => entry.title.includes('Abbey Normal Golem Head')))) throw new Error('MM7 item rows missing from search');
if (!serviceWorker.includes('assets/mm7/maps/avlee.gif')) throw new Error('MM7 map missing from offline cache');
const travelSource = await readFile(path.join(dist, 'mm7-travel-data.js'), 'utf8');
const travelMatch = travelSource.match(/^window\.MM7_TRAVEL=(.*);\s*$/s);
if (!travelMatch) throw new Error('Invalid MM7 travel bundle');
const travel = JSON.parse(travelMatch[1]);
if (travel.services.length !== 13 || travel.trips.length !== 78) throw new Error('Incomplete MM7 transportation schedule');
for (const trip of travel.trips) if (!travel.positions[trip.origin] || !travel.positions[trip.destination]) throw new Error(`Unmapped MM7 trip: ${trip.origin} to ${trip.destination}`);
if (!travel.trips.some(trip => trip.origin === 'Harmondale' && trip.destination === 'Arena' && trip.day === 'Sunday')) throw new Error('Arena route missing');
if (!travel.trips.some(trip => trip.service === 'Sea Sprite' && trip.destination === 'Bracada Desert')) throw new Error('Bracada route typo was not normalized');
if (!serviceWorker.includes('globe/img/antagarich.webp') || !serviceWorker.includes('mm7-travel-data.js')) throw new Error('MM7 travel map is not available offline');
console.log(`Verified ${pages.length} pages and all ${pages.reduce((n, p) => n + p.images.length, 0)} referenced images.`);
console.log(`Verified ${openyamm.maps.length} detailed maps and ${openyamm.maps.reduce((count, map) => count + map.pois.length, 0)} mapped places.`);
console.log(`Verified ${mm7Pages.length} MM7 pages and linked offline images.`);
console.log(`Verified ${travel.services.length} MM7 travel services and ${travel.trips.length} scheduled trips.`);
